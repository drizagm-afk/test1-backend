CREATE TABLE CARRERAS (
    carrera_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL UNIQUE,
    descripcion VARCHAR2(250),
    estado BOOLEAN NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP NOT NULL
);

CREATE TABLE CURSOS (
    curso_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL UNIQUE,
    creditos NUMBER NOT NULL,
    estado BOOLEAN NOT NULL,
    carrera_id NUMBER NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP NOT NULL,
    CONSTRAINT fk_curso_carrera FOREIGN KEY (carrera_id)
        REFERENCES CARRERAS(carrera_id)
);

CREATE TABLE ESTUDIANTES (
    estudiante_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(15) NOT NULL UNIQUE,
    nombres VARCHAR2(100) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    estado BOOLEAN NOT NULL,
    carrera_id NUMBER NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP NOT NULL,
    CONSTRAINT fk_estudiante_carrera FOREIGN KEY (carrera_id)
        REFERENCES CARRERAS(carrera_id)
);